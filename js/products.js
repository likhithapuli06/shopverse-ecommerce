// Helper functions for products
export function getProductById(id) {
  return products.find(p => p.id === parseInt(id));
}

export function getProductsByCategory(category) {
  if (!category || category === 'All' || category.toLowerCase() === 'all') return products;
  const target = category.toLowerCase().trim();
  return products.filter(p => {
    const cat = p.category.toLowerCase().trim();
    if (cat === target) return true;
    // Map Women's Clothing <-> Women's Fashion
    if (target.includes('women') && cat.includes('women')) return true;
    // Map Men's Clothing <-> Men's Fashion
    if (target.includes('men') && !target.includes('women') && cat.includes('men') && !cat.includes('women')) return true;
    return false;
  });
}

export function searchProducts(query) {
  if (!query) return products;
  const q = query.toLowerCase().trim();
  return products.filter(p => 
    p.name.toLowerCase().includes(q) || 
    p.category.toLowerCase().includes(q) ||
    (p.description && p.description.toLowerCase().includes(q))
  );
}

// Expose products and functions to the window object for global module and script accessibility
if (typeof window !== 'undefined') {
  window.products = products;
  window.getProductById = getProductById;
  window.getProductsByCategory = getProductsByCategory;
  window.searchProducts = searchProducts;
}
